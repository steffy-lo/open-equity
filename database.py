def _ensure_signal_columns() -> None:
    inspector = inspect(engine)
    tables = set(inspector.get_table_names())
    if "signal" not in tables:
        return

    existing = {column["name"] for column in inspector.get_columns("signal")}
    migrations = {
        "screen_scope": "ALTER TABLE signal ADD COLUMN screen_scope VARCHAR",
        "screen_label": "ALTER TABLE signal ADD COLUMN screen_label VARCHAR",
        "universe": "ALTER TABLE signal ADD COLUMN universe VARCHAR",
        "watchlist_member": "ALTER TABLE signal ADD COLUMN watchlist_member BOOLEAN DEFAULT 0",
    }

    with engine.begin() as conn:
        for column, ddl in migrations.items():
            if column not in existing:
                conn.execute(text(ddl))

def _ensure_pipeline_columns() -> None:
    """
    Migration-safe column additions for ResearchBrief and BlogPost.
    Mirrors the pattern of _ensure_signal_columns().
    Run after SQLModel.metadata.create_all() so the tables exist.
    """
    from sqlalchemy import inspect, text
 
    inspector = inspect(engine)
    existing_tables = set(inspector.get_table_names())
 
    migrations: dict[str, dict[str, str]] = {
        "researchbrief": {
            "earnings_watch": "ALTER TABLE researchbrief ADD COLUMN earnings_watch VARCHAR DEFAULT '[]'",
            "raw_json":       "ALTER TABLE researchbrief ADD COLUMN raw_json VARCHAR",
        },
        "blogpost": {
            "spy_return_pct": "ALTER TABLE blogpost ADD COLUMN spy_return_pct FLOAT",
            "iso_week":       "ALTER TABLE blogpost ADD COLUMN iso_week VARCHAR",
        },
    }
 
    with engine.begin() as conn:
        for table, columns in migrations.items():
            if table not in existing_tables:
                continue
            existing_cols = {c["name"] for c in inspector.get_columns(table)}
            for col_name, ddl in columns.items():
                if col_name not in existing_cols:
                    conn.execute(text(ddl))


def init_db() -> None:
    SQLModel.metadata.create_all(engine)
    _ensure_signal_columns()
    _ensure_pipeline_columns()


def get_session() -> Generator[Session, None, None]:
    with Session(engine) as session:
        yield session


@contextmanager
def session_scope() -> Generator[Session, None, None]:
    with Session(engine) as session:
        yield session
