class ResearchBrief(SQLModel, table=True):
    """
    One row per weekly research run (Monday morning).
    Stores the structured output from the Claude research agent.
    """
    id:             Optional[int]  = Field(default=None, primary_key=True)
    week_of:        str            = Field(index=True)          # "YYYY-MM-DD" (Monday)
    strategy:       str            = ""                          # momentum | mean_reversion | ...
    time_horizon:   str            = ""                          # e.g. "3-5 day swing"
    risk_posture:   str            = "moderate"                  # aggressive | moderate | conservative
    themes:         str            = "[]"                        # JSON list
    focus_sectors:  str            = "[]"                        # JSON list
    avoid_sectors:  str            = "[]"                        # JSON list
    watchlist_add:  str            = "[]"                        # JSON list of tickers added
    watchlist_remove: str          = "[]"                        # JSON list of tickers removed
    earnings_watch: str            = "[]"                        # JSON list of tickers with catalysts
    macro_summary:  str            = ""
    key_risks:      str            = ""
    rationale:      str            = ""
    raw_json:       Optional[str]  = None                        # full JSON from Claude
    created_at:     datetime       = Field(default_factory=datetime.utcnow, index=True)
 
 
class BlogPost(SQLModel, table=True):
    """
    One row per weekly blog post (Sunday evening).
    Content is raw markdown generated by the Claude blog agent.
    """
    id:             Optional[int]  = Field(default=None, primary_key=True)
    week_of:        str            = Field(index=True)           # "YYYY-MM-DD" (Monday of that week)
    iso_week:       str            = Field(index=True)           # "YYYY-WNN"
    title:          str            = ""
    summary:        str            = ""                          # executive summary paragraph
    content:        str            = ""                          # full markdown
    week_pnl:       float          = 0.0                         # realized P&L for the week
    spy_return_pct: Optional[float]= None                        # SPY weekly return %
    trades_count:   int            = 0
    strategy:       str            = ""                          # strategy from research brief
    created_at:     datetime       = Field(default_factory=datetime.utcnow, index=True)


engine = create_engine(
    f"sqlite:///{DB_PATH}",
    connect_args={"check_same_thread": False},
)

